#!/usr/bin/env node
/**
 * Generates src/content/scripture/bsb.generated.ts from the official
 * Berean Standard Bible (BSB) verse-per-line edition published by eBible.org.
 *
 * The BSB is dedicated to the public domain by BSB Publishing, LLC
 * (see https://ebible.org/find/details.php?id=engbsb). Verses are copied
 * verbatim; nothing in this script edits wording or punctuation.
 *
 * Usage:
 *   node scripts/extract-scripture.mjs                # downloads engbsb_vpl.zip
 *   node scripts/extract-scripture.mjs path/to/engbsb_vpl.txt
 *
 * Add references to VERSES below when new content quotes Scripture; the unit
 * test src/content/content.test.ts fails if content cites a verse that is
 * missing from the generated store.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const SOURCE_URL = 'https://ebible.org/Scriptures/engbsb_vpl.zip';
const OUT_FILE = path.join(import.meta.dirname, '..', 'src', 'content', 'scripture', 'bsb.generated.ts');

/** Verse ranges quoted by Milestone 1 content: [book, chapter, firstVerse, lastVerse]. */
const VERSES = [
  ['GEN', 9, 13, 13],
  ['EXO', 14, 21, 22],
  ['JOS', 1, 9, 9],
  ['RUT', 1, 16, 17],
  ['1SA', 16, 7, 7],
  ['1SA', 16, 11, 13],
  ['1SA', 17, 3, 4],
  ['1SA', 17, 32, 37],
  ['1SA', 17, 40, 40],
  ['1SA', 17, 45, 47],
  ['1SA', 17, 49, 50],
  ['2SA', 5, 3, 4],
  ['1KI', 18, 36, 39],
  ['EST', 4, 14, 14],
  ['PSA', 23, 1, 3],
  ['DAN', 6, 22, 22],
];

/** Minimal reader for a ZIP holding a single deflated text entry (no dependencies). */
const readZipEntry = (buffer, wantedSuffix) => {
  let eocd = buffer.length - 22;
  while (eocd >= 0 && buffer.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('Not a zip archive');
  const entries = buffer.readUInt16LE(eocd + 10);
  let ptr = buffer.readUInt32LE(eocd + 16);
  for (let i = 0; i < entries; i++) {
    const method = buffer.readUInt16LE(ptr + 10);
    const compressedSize = buffer.readUInt32LE(ptr + 20);
    const nameLength = buffer.readUInt16LE(ptr + 28);
    const extraLength = buffer.readUInt16LE(ptr + 30);
    const commentLength = buffer.readUInt16LE(ptr + 32);
    const localOffset = buffer.readUInt32LE(ptr + 42);
    const name = buffer.toString('utf8', ptr + 46, ptr + 46 + nameLength);
    if (name.endsWith(wantedSuffix)) {
      const localNameLength = buffer.readUInt16LE(localOffset + 26);
      const localExtraLength = buffer.readUInt16LE(localOffset + 28);
      const start = localOffset + 30 + localNameLength + localExtraLength;
      const data = buffer.subarray(start, start + compressedSize);
      return (method === 0 ? data : zlib.inflateRawSync(data)).toString('utf8');
    }
    ptr += 46 + nameLength + extraLength + commentLength;
  }
  throw new Error(`Entry *${wantedSuffix} not found in archive`);
};

const loadSource = async () => {
  const localPath = process.argv[2];
  if (localPath) return fs.readFileSync(localPath, 'utf8');
  console.log(`Downloading ${SOURCE_URL}`);
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Download failed: HTTP ${response.status}`);
  return readZipEntry(Buffer.from(await response.arrayBuffer()), '_vpl.txt');
};

const text = await loadSource();
const index = new Map();
for (const line of text.split(/\r?\n/)) {
  const match = /^(\S+) (\d+):(\d+) (.*)$/.exec(line.replace(/^﻿/, ''));
  if (match) index.set(`${match[1]} ${match[2]}:${match[3]}`, match[4].trim());
}

const out = {};
for (const [book, chapter, first, last] of VERSES) {
  for (let verse = first; verse <= last; verse++) {
    const key = `${book} ${chapter}:${verse}`;
    const value = index.get(key);
    if (!value) throw new Error(`Verse ${key} not found in source`);
    out[key] = value;
  }
}

const body = Object.entries(out)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join('\n');

fs.writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/extract-scripture.mjs — do not edit by hand.
// Source: Berean Standard Bible (BSB), public domain, via ${SOURCE_URL}
// Verses are verbatim. Regenerate with: node scripts/extract-scripture.mjs

export const BSB_VERSES: Readonly<Record<string, string>> = {
${body}
};
`,
);
console.log(`Wrote ${Object.keys(out).length} verses to ${path.relative(process.cwd(), OUT_FILE)}`);
